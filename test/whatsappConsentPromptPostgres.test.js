"use strict";

const test=require("node:test");
const assert=require("node:assert/strict");
const {Client,Pool}=require("pg");
const fs=require("node:fs");
const path=require("node:path");
const repo=require("../src/db/whatsappConsentPromptRepo");
const connectionString=process.env.TEST_DATABASE_URL;

test("Postgres final consent: eligible FU3 -> atomic prompt -> verified button opt-in",
 {skip:!connectionString}, async()=>{
  const admin=new Client({connectionString});
  const schema="consent_prompt_"+process.pid+"_"+Date.now();
  await admin.connect();
  let pool;
  try {
    await admin.query("CREATE SCHEMA "+schema);
    await admin.query("SET search_path TO "+schema);
    await admin.query(`
      CREATE TABLE contacts (
        id INTEGER PRIMARY KEY, channel TEXT, whatsapp_number TEXT,mode TEXT,
        needs_attention BOOLEAN DEFAULT false, attention_reason TEXT,
        whatsapp_opt_in_at TIMESTAMPTZ,whatsapp_opt_in_source TEXT,
        whatsapp_opt_out_at TIMESTAMPTZ,whatsapp_marketing_opt_out_at TIMESTAMPTZ,
        whatsapp_marketing_opt_out_source TEXT, updated_at TIMESTAMPTZ
      );
      CREATE TABLE pipeline_stages(id INTEGER PRIMARY KEY,stage_type TEXT,system_key TEXT);
      CREATE TABLE leads(id INTEGER PRIMARY KEY,contact_id INTEGER REFERENCES contacts(id),
        treatment_interest TEXT, marketing_consent TEXT,is_closed BOOLEAN,
        appointment_status TEXT,stage_id INTEGER,created_at TIMESTAMPTZ,
        updated_at TIMESTAMPTZ);
      CREATE TABLE messages(
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        contact_id INTEGER REFERENCES contacts(id),role TEXT,content TEXT,
        created_at TIMESTAMPTZ DEFAULT now(),source_created_at TIMESTAMPTZ,
        sent_by_username TEXT,is_automated_follow_up BOOLEAN DEFAULT false,
        automated_follow_up_step INTEGER DEFAULT 1,
        automated_follow_up_for_message_id INTEGER,
        automated_follow_up_message_mode TEXT, whatsapp_accepted_at TIMESTAMPTZ,
        whatsapp_message_id TEXT,delivery_status TEXT,delivery_error TEXT,
        pricing_reminder_anchor_id INTEGER, is_forwarded BOOLEAN DEFAULT false,
        media_mime_type TEXT
      );
      CREATE TABLE outbound_message_evidence(message_id INTEGER,origin TEXT);
      CREATE TABLE ai_review_items(contact_id INTEGER,status TEXT,category TEXT);
      CREATE TABLE follow_up_ai_decisions(contact_id INTEGER,trigger_message_id INTEGER,action TEXT);
      CREATE TABLE whatsapp_marketing_consent_events(
        id BIGSERIAL PRIMARY KEY, contact_id INTEGER, lead_id INTEGER, source TEXT,
        recorded_by TEXT,message_id INTEGER UNIQUE,provider_message_id TEXT,
        message_text TEXT,business_name TEXT,consent_scope TEXT,
        consent_category TEXT,consented_at TIMESTAMPTZ,consent_method TEXT,
        consent_service TEXT
      );
    `);
    await admin.query(fs.readFileSync(path.join(__dirname,
      "../src/db/migrations/067_whatsapp_final_consent_prompt.sql"),"utf8"));
    await admin.query(`
      INSERT INTO contacts(id,channel,whatsapp_number,mode,needs_attention)
      VALUES(1,'whatsapp','60123456789','ai',false);
      INSERT INTO pipeline_stages(id,stage_type,system_key) VALUES(1,'open','new');
      INSERT INTO leads(id,contact_id,treatment_interest,marketing_consent,
        is_closed,appointment_status,stage_id,created_at)
      VALUES(1,1,'骨盆调理','unknown',false,'none',1,now()-interval '22 hours');
      INSERT INTO messages(id,contact_id,role,content,created_at,whatsapp_message_id)
      VALUES(10,1,'user','了解骨盆调理',now()-interval '20 hours','wamid.inbound');
      INSERT INTO messages(id,contact_id,role,content,created_at,sent_by_username)
      VALUES(11,1,'assistant','您好',now()-interval '19 hours','AI');
      INSERT INTO messages(id,contact_id,role,content,created_at,
        is_automated_follow_up,automated_follow_up_step,
        automated_follow_up_for_message_id,whatsapp_accepted_at,
        whatsapp_message_id,delivery_status)
      VALUES(12,1,'assistant','Follow-up 3',now()-interval '30 minutes',
        true,3,11,now()-interval '20 minutes','wamid.fu3','delivered');
    `);
    pool=new Pool({connectionString,options:"-c search_path="+schema,max:3});
    const activatedAt=new Date(Date.now()-21*60*60*1000).toISOString();
    const settings={activatedAt,triggerMode:"all",now:new Date()};
    const rows=await repo.listCandidates(settings,pool);
    assert.equal(rows.length,1,"accepted FU3 makes the current silent chat eligible");
    const question="对了～之后如果有关于骨盆调理的资讯或相关优惠，Neutro Sense TCM 可以继续 WhatsApp 跟进通知您吗？😊";
    const prompt=await repo.claim(rows[0],{...settings,question},pool);
    assert.ok(prompt?.promptId);
    assert.equal(prompt.question,question);
    assert.equal(await repo.stillEligible(prompt,settings,pool),true);
    assert.equal(await repo.claim(rows[0],{...settings,question},pool),null,
      "same lead cannot receive a second prompt under concurrent workers");
    const record=await pool.query(
      "SELECT status,message_id FROM whatsapp_consent_prompts WHERE id=$1",
      [prompt.promptId]);
    assert.equal(record.rows[0].status,"claimed");
    await pool.query("UPDATE whatsapp_consent_prompts SET status='accepted' WHERE id=$1",
      [prompt.promptId]);
    await pool.query(`INSERT INTO messages(id,contact_id,role,content,created_at,
      whatsapp_message_id) VALUES(101,1,'user','同意接收跟进优惠',now(),'wamid.tap.yes')`);
    const yes=await repo.recordButtonResponse({
      contactId:1,messageId:101,leadId:1,
      replyId:"da_consent_yes:"+prompt.promptId,businessName:"Neutro Sense TCM Centre",
    },{database:pool});
    assert.equal(yes.handled,true);
    assert.equal(yes.decision,"accepted");
    const consent=await pool.query(`
      SELECT c.whatsapp_opt_in_source,l.marketing_consent,e.consent_service,
       e.consent_method,e.provider_message_id
      FROM contacts c JOIN leads l ON l.contact_id=c.id
      JOIN whatsapp_marketing_consent_events e ON e.contact_id=c.id WHERE c.id=1`);
    assert.equal(consent.rows[0].whatsapp_opt_in_source,"customer_whatsapp_button");
    assert.equal(consent.rows[0].marketing_consent,"opted_in");
    assert.equal(consent.rows[0].consent_service,"骨盆调理");
    assert.equal(consent.rows[0].provider_message_id,"wamid.tap.yes");
    const replay=await repo.recordButtonResponse({
      contactId:1,messageId:101,leadId:1,
      replyId:"da_consent_yes:"+prompt.promptId,businessName:"Neutro Sense TCM Centre",
    },{database:pool});
    assert.equal(replay.alreadyRecorded,true);
  } finally {
    await pool?.end().catch(()=>{});
    await admin.query("DROP SCHEMA IF EXISTS "+schema+" CASCADE").catch(()=>{});
    await admin.end();
  }
});
